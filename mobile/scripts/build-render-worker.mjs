// Builds the render worker page (render-worker/worker.ts) into one HTML
// string the app loads into a hidden WebView: src/render/workerHtml.generated.ts.
//
// Run after building the shared libraries, and again whenever they or the
// worker change:  npm run worker
//
// pdf.js comes from desktop/converter's node_modules, so the app and the
// desktop use one copy.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const mobile = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(mobile, '..');

const result = await build({
  entryPoints: [join(mobile, 'render-worker/worker.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['chrome100'],
  minify: true,
  legalComments: 'none',
  nodePaths: [join(repo, 'desktop/converter/node_modules'), join(mobile, 'node_modules')],
  // pdf.js's legacy build only reaches for these under Node.
  external: ['fs', 'path', 'url', 'http', 'https', 'zlib', 'canvas', '@napi-rs/canvas', 'module'],
  logLevel: 'warning',
});

const script = result.outputFiles[0].text.replace(/<\/script/giu, '<\\/script');
const html = `<!doctype html><html><head><meta charset="utf-8"></head><body><script>${script}</script></body></html>`;

const out = join(mobile, 'src/render/workerHtml.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-render-worker.mjs from render-worker/worker.ts. Do not edit.\n` +
    `export default ${JSON.stringify(html)};\n`,
);
// A copy to open in a desktop browser when debugging the worker.
writeFileSync(join(mobile, 'render-worker/worker.generated.html'), html);
console.log(`wrote ${out} (${(html.length / 1024 / 1024).toFixed(1)} MB)`);
